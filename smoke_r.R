args <- commandArgs(TRUE)
if(length(args)>=3 && nzchar(args[[3]])) .libPaths(c(args[[3]],.libPaths()))
library(datapond)
library(DBI)
pilot <- identical(args[[4]],'true')
options(datapond.registry_url=args[[1]],datapond.cache_dir=args[[2]])
stopifnot(identical(dp_list(),'uscis'))
con <- dp_connect('uscis',quiet=TRUE)
tryCatch({
  dbExecute(con,"SET memory_limit='128MiB'")
  dbExecute(con,'SET threads=1')
  dbExecute(con,"SET max_temp_directory_size='0B'")
  stopifnot(dbGetQuery(con,'SELECT count(*) n FROM daca_applications')$n==if(pilot)2048 else 4526373)
  stopifnot(dbGetQuery(con,'SELECT count(*) n FROM tps_applications')$n==if(pilot)2048 else 6680172)
  stopifnot(nrow(dp_describe(con))==2)
  stopifnot(dbGetQuery(con,'SELECT count(*) n FROM _columns')$n==63)
  provenance <- dbGetQuery(con,'SELECT is_pilot FROM _provenance')
  stopifnot(nrow(provenance)==2,all(provenance$is_pilot==pilot))
  script_arg <- grep('^--file=',commandArgs(FALSE),value=TRUE)
  definitions <- jsonlite::fromJSON(file.path(dirname(sub('^--file=','',script_arg)),'field-definitions.json'),simplifyVector=FALSE)
  columns <- dbGetQuery(con,'SELECT column_name,description,join_hint FROM _columns')
  for(i in seq_len(nrow(columns))) {
    definition <- definitions[[columns$column_name[[i]]]]
    stopifnot(identical(columns$description[[i]],definition$description))
    if(is.null(definition$join_hint)) stopifnot(is.na(columns$join_hint[[i]])) else stopifnot(identical(columns$join_hint[[i]],definition$join_hint))
  }
  example <- dbGetQuery(con,'SELECT data_source, count(*) AS application_rows FROM daca_applications GROUP BY data_source ORDER BY data_source')
  cat(jsonlite::toJSON(list(passed=TRUE,is_pilot=pilot,client='R datapond',version=as.character(packageVersion('datapond')),duckdb=as.character(packageVersion('duckdb')),example=example),auto_unbox=TRUE))
},finally=dp_disconnect(con))
